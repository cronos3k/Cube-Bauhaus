//! Minimal bitmap text renderer for screenshot overlays.
//! 5×7 pixel font covering ASCII 32-126, drawn directly into an RGBA pixel buffer.

/// Burn a string of text into an RGBA pixel buffer at (x, y) in the given color.
/// Each character is 5×7 pixels with 1px spacing.  A dark outline is drawn behind
/// the text for readability on any background.
pub fn burn_text(rgba: &mut [u8], img_w: u32, img_h: u32, x: u32, y: u32, text: &str, color: [u8; 4]) {
    let outline = [0u8, 0, 0, 220];
    // First pass: draw dark outline (shifted by ±1 in each direction)
    for dy in [-1i32, 0, 1] {
        for dx in [-1i32, 0, 1] {
            if dx == 0 && dy == 0 { continue; }
            draw_text_raw(rgba, img_w, img_h,
                (x as i32 + dx).max(0) as u32,
                (y as i32 + dy).max(0) as u32,
                text, outline);
        }
    }
    // Second pass: draw foreground text
    draw_text_raw(rgba, img_w, img_h, x, y, text, color);
}

fn draw_text_raw(rgba: &mut [u8], img_w: u32, img_h: u32, x: u32, y: u32, text: &str, color: [u8; 4]) {
    let mut cx = x;
    for ch in text.chars() {
        let glyph = glyph_for(ch);
        for row in 0..7u32 {
            for col in 0..5u32 {
                if (glyph[row as usize] >> (4 - col)) & 1 != 0 {
                    let px = cx + col;
                    let py = y + row;
                    if px < img_w && py < img_h {
                        let off = ((py * img_w + px) * 4) as usize;
                        rgba[off]     = color[0];
                        rgba[off + 1] = color[1];
                        rgba[off + 2] = color[2];
                        rgba[off + 3] = color[3];
                    }
                }
            }
        }
        cx += 6; // 5 pixels wide + 1 pixel gap
    }
}

